"""Comprehensive disk hygiene, cache purging, and installer reclaimer engine."""

import os
import shutil
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Tuple
from winget_updater.utils.logger import get_logger
from winget_updater.utils.process import silent_run

logger = get_logger()


class DiskCleanupManager:
    """Scans and reclaims disk space from installer caches, diagnostic logs, and temp residues."""

    @staticmethod
    def get_cleanup_targets() -> List[Dict[str, Any]]:
        """Returns definitions of all purgeable disk cache targets with dynamic path expansion."""
        local_app_data = os.environ.get("LOCALAPPDATA", "")
        temp_dir = tempfile.gettempdir()

        targets = [
            {
                "id": "winget_installers",
                "name": "WinGet Installer Download Cache",
                "description": "Cached .exe, .msi, and .msix setup binaries downloaded during package upgrades.",
                "paths": [
                    str(Path(local_app_data) / "Temp" / "WinGet") if local_app_data else "",
                    str(Path(temp_dir) / "WinGet"),
                ],
                "safe": True,
            },
            {
                "id": "winget_logs",
                "name": "WinGet Diagnostic & Session Logs",
                "description": "Accumulated trace and diagnostic logs generated by Windows Package Manager.",
                "paths": [
                    str(Path(local_app_data) / "Packages" / "Microsoft.DesktopAppInstaller_8wekyb3d8bbwe" / "LocalState" / "DiagOutputDir") if local_app_data else "",
                    str(Path(local_app_data) / "Microsoft" / "WinGet" / "Logs") if local_app_data else "",
                ],
                "safe": True,
            },
            {
                "id": "vendor_cache",
                "name": "Updater Vendor Extraction Cache",
                "description": "Temporary installer downloads from vendor fallback and direct URL updates.",
                "paths": [
                    str(Path(temp_dir) / "winget_updater_vendor"),
                ],
                "safe": True,
            },
            {
                "id": "updater_logs",
                "name": "Updater Rollback & Session Logs",
                "description": "Historical update session logs and transient restore staging files.",
                "paths": [
                    str(Path(local_app_data) / "winget_updater" / "logs") if local_app_data else "",
                    str(Path(temp_dir) / "winget_updater_logs"),
                ],
                "safe": True,
            },
        ]
        return targets

    @classmethod
    def scan_targets(cls) -> List[Dict[str, Any]]:
        """Scans all defined targets and returns byte counts, file counts, and valid directory paths."""
        target_defs = cls.get_cleanup_targets()
        scanned_results = []

        for target in target_defs:
            seen_files = set()
            total_bytes = 0
            file_count = 0
            resolved_paths = []

            for p_raw in target.get("paths", []):
                if not p_raw:
                    continue
                p = Path(os.path.expandvars(p_raw))
                if p.exists():
                    resolved_str = str(p.resolve())
                    if resolved_str not in resolved_paths:
                        resolved_paths.append(resolved_str)
                    try:
                        if p.is_dir():
                            for entry in p.rglob("*"):
                                try:
                                    if entry.is_file():
                                        abs_path = str(entry.resolve()).lower()
                                        if abs_path not in seen_files:
                                            seen_files.add(abs_path)
                                            total_bytes += entry.stat().st_size
                                            file_count += 1
                                except Exception:
                                    continue
                        elif p.is_file():
                            abs_path = str(p.resolve()).lower()
                            if abs_path not in seen_files:
                                seen_files.add(abs_path)
                                total_bytes += p.stat().st_size
                                file_count += 1
                    except Exception as e:
                        logger.debug(f"Scan error for {p}: {e}")

            mb = total_bytes / (1024 * 1024)
            scanned_results.append({
                "id": target["id"],
                "name": target["name"],
                "description": target["description"],
                "paths": resolved_paths,
                "bytes": total_bytes,
                "mb": round(mb, 2),
                "formatted_size": f"{mb:.2f} MB" if mb < 1024 else f"{mb / 1024:.2f} GB",
                "files_count": file_count,
                "safe": target.get("safe", True),
            })

        return scanned_results

    @classmethod
    def purge_targets(cls, target_ids: List[str]) -> Dict[str, Any]:
        """Safely purges the specified target categories. Handles locked files gracefully."""
        all_targets = {t["id"]: t for t in cls.get_cleanup_targets()}
        freed_bytes = 0
        removed_files = 0
        errors = []

        for tid in target_ids:
            if tid not in all_targets:
                continue
            target = all_targets[tid]
            seen_dirs = set()

            for p_raw in target.get("paths", []):
                if not p_raw:
                    continue
                p = Path(os.path.expandvars(p_raw))
                if not p.exists():
                    continue

                if p.is_dir():
                    try:
                        resolved_dir = str(p.resolve()).lower()
                        if resolved_dir in seen_dirs:
                            continue
                        seen_dirs.add(resolved_dir)

                        for item in list(p.iterdir()):
                            try:
                                if item.is_file():
                                    sz = item.stat().st_size
                                    item.unlink(missing_ok=True)
                                    freed_bytes += sz
                                    removed_files += 1
                                elif item.is_dir():
                                    dir_size = sum(f.stat().st_size for f in item.rglob("*") if f.is_file())
                                    dir_files = sum(1 for f in item.rglob("*") if f.is_file())
                                    shutil.rmtree(item, ignore_errors=True)
                                    freed_bytes += dir_size
                                    removed_files += dir_files
                            except Exception as ex:
                                errors.append(f"{item.name}: {ex}")
                    except Exception as e:
                        errors.append(f"{p}: {e}")
                elif p.is_file():
                    try:
                        sz = p.stat().st_size
                        p.unlink(missing_ok=True)
                        freed_bytes += sz
                        removed_files += 1
                    except Exception as ex:
                        errors.append(f"{p.name}: {ex}")

        mb_freed = freed_bytes / (1024 * 1024)
        msg = f"Cleaned {mb_freed:.2f} MB across {removed_files} installer files."
        logger.info(msg)
        return {
            "freed_bytes": freed_bytes,
            "freed_mb": round(mb_freed, 2),
            "removed_files": removed_files,
            "errors": errors,
            "summary": msg,
        }

    @classmethod
    def cleanup_temp_and_cache(cls, winget_path: str = "winget") -> Tuple[int, str]:
        """Legacy compatibility wrapper used by auto-updater flows."""
        res = cls.purge_targets(["winget_installers", "vendor_cache"])
        try:
            silent_run([winget_path, "cache", "purge", "--force"], capture_output=True, timeout=15)
        except Exception:
            pass
        return res["freed_bytes"], res["summary"]
